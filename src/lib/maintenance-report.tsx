function ReportKpiCard({ label, value, accent }: { label: string; value: string; accent: string }) {
  return (
    <div style={{ border: "1px solid #e2e8f0", borderRadius: 10, padding: "14px 16px", background: "#ffffff" }}>
      <p style={{ margin: 0, fontSize: 10, fontWeight: 700, letterSpacing: 0.6, textTransform: "uppercase", color: "#64748b" }}>
        {label}
      </p>
      <p style={{ margin: "6px 0 0", fontSize: 22, fontWeight: 800, color: accent }}>{value}</p>
    </div>
  );
}

function DowntimeBar({ label, minutes, pct, color }: { label: string; minutes: number; pct: number; color: string }) {
  return (
    <div style={{ marginBottom: 18 }}>
      <div style={{ display: "flex", justifyContent: "space-between", fontSize: 13, marginBottom: 6 }}>
        <span style={{ fontWeight: 700, color: "#1e293b" }}>{label}</span>
        <span style={{ color: "#64748b" }}>
          {Math.round(minutes)} min · {pct.toFixed(1)}%
        </span>
      </div>
      <div style={{ height: 18, borderRadius: 6, background: "#f1f5f9", overflow: "hidden" }}>
        <div style={{ height: "100%", width: `${minutes > 0 ? Math.max(pct, 2) : 0}%`, background: color }} />
      </div>
    </div>
  );
}

// Same visual language as DowntimeBar but for a plain count rather than a
// minutes+percentage-of-whole pair (frequency bars compare "how many times"
// not "how much of the total").
function FrequencyBar({ label, count, pct, color }: { label: string; count: number; pct: number; color: string }) {
  return (
    <div style={{ marginBottom: 14 }}>
      <div style={{ display: "flex", justifyContent: "space-between", fontSize: 12, marginBottom: 4 }}>
        <span style={{ fontWeight: 700, color: "#1e293b" }}>{label}</span>
        <span style={{ color: "#64748b" }}>
          {count} event{count === 1 ? "" : "s"}
        </span>
      </div>
      <div style={{ height: 14, borderRadius: 6, background: "#f1f5f9", overflow: "hidden" }}>
        <div style={{ height: "100%", width: `${count > 0 ? Math.max(pct, 3) : 0}%`, background: color }} />
      </div>
    </div>
  );
}

