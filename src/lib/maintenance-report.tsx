export interface MaintenanceReportOptions {
  lineName: string;
  from: string | null;
  to: string | null;
  // Display name (or email fallback) of the user who triggered the export —
  // shown in the page-1 header as "Generated by", distinct from the
  // generation timestamp.
  generatedBy: string;
  // Currently-filtered events (line/type/status/date filters from the
  // /maintenance page) — this is the "what got exported" set, used for the
  // events table and the Mechanical vs Electrical downtime chart.
  events: MaintenanceEvent[];
  // Lifetime, unfiltered MTBF/MTTR by Line & Type — same semantics as the
  // live page's own metrics table (its own doc comment: "not affected by
  // the table filters above"), reused as-is for consistency.
  metrics: MaintenanceMetric[];
  // Plant-wide summary numbers, already computed by the caller (same values
  // as the live page's own top KPI cards) — this module only presents them,
  // it doesn't re-derive MTBF/MTTR math itself.
  totalEvents: number;
  openCount: number;
  // Preventive events are kept out of openCount (which feeds the same
  // mechanical/electrical-only reliability story as the KPI cards above it)
  // and shown as its own card instead — see MaintenanceType docs.
  openPreventiveCount: number;
  mtbfMechanicalHours: number | null;
  mttrMechanicalHours: number | null;
  mtbfElectricalHours: number | null;
  mttrElectricalHours: number | null;
  // Reliability Analytics numbers — the exact same values already computed
  // by the live /maintenance page's own useMemo hooks (see
  // src/routes/maintenance.tsx), passed through rather than re-derived here,
  // so the report can never drift from what the page shows for the same
  // filter. topLossesByDowntime/topLossesByFrequency are sliced to the top 5
  // by the caller (or here, defensively); chronicVsSporadic is passed in
  // full so the summary counts below are accurate, not just the visible
  // slice.
  totalDowntimeMinutes: number;
  repeatFailureRatePct: number;
  availabilityPct: number | null;
  topLossesByDowntime: { title: string; totalMinutes: number }[];
  topLossesByFrequency: { title: string; count: number }[];
  chronicVsSporadic: { title: string; count: number; chronic: boolean }[];
  reliabilityByLine: { lineName: string; mtbfHours: number | null; mttrHours: number | null; availabilityPct: number | null; eventCount: number }[];
  onProgress?: (message: string) => void;
}

interface LogoInfo {
  dataUrl: string;
  widthPt: number;
  heightPt: number;
}

// Duplicated from pdf-export.ts rather than shared, deliberately — keeps
// this report isolated from the main dashboard exporter so a change to one
// can't regress the other. Same behavior: logo is optional, export proceeds
// without it if /logo.png can't be loaded.
async function loadLogo(): Promise<LogoInfo | null> {
  try {
    const res = await fetch("/logo.png");
    if (!res.ok) return null;
    const blob = await res.blob();
    const dataUrl: string = await new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result as string);
      reader.onerror = reject;
      reader.readAsDataURL(blob);
    });
    const img = await loadImage(dataUrl);
    const scale = img.height > LOGO_MAX_HEIGHT ? LOGO_MAX_HEIGHT / img.height : 1;
    return { dataUrl, widthPt: img.width * scale, heightPt: img.height * scale };
  } catch {
    return null;
  }
}

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = reject;
    img.src = src;
  });
}

// Same pixel-slicing fallback as pdf-export.ts, for a section (typically the
// events table, if the current filters match many rows) taller than one
// full page — always starts on its own fresh page so no other section
// shares the break, even though a table row could itself land on a slice
// boundary. Accepted tradeoff, same as the main dashboard exporter.
function drawOversizedSection(
  doc: jsPDF,
  img: HTMLImageElement,
  contentWidth: number,
  maxContentHeight: number,
  pxPerPt: number,
): void {
  let sourceY = 0;
  let remainingPx = img.height;
  let firstSlice = true;

  while (remainingPx > 0) {
    const availablePx = Math.floor(maxContentHeight * pxPerPt);
    const slicePx = Math.min(availablePx, remainingPx);

    const canvas = document.createElement("canvas");
    canvas.width = img.width;
    canvas.height = slicePx;
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Canvas 2D context unavailable");
    ctx.drawImage(img, 0, sourceY, img.width, slicePx, 0, 0, img.width, slicePx);

    const sliceHeightPt = slicePx / pxPerPt;
    if (!firstSlice) doc.addPage();
    doc.addImage(
      canvas.toDataURL("image/jpeg", JPEG_QUALITY),
      "JPEG",
      PAGE_MARGIN,
      PAGE_MARGIN,
      contentWidth,
      sliceHeightPt,
      undefined,
      "FAST",
    );

    sourceY += slicePx;
    remainingPx -= slicePx;
    firstSlice = false;
  }
}

function eventDurationMinutes(e: MaintenanceEvent): number {
  const start = new Date(e.started_at).getTime();
  const end = e.resolved_at ? new Date(e.resolved_at).getTime() : Date.now();
  return Math.max(0, (end - start) / 60_000);
}

function personLabel(p: { display_name: string | null; email: string } | null): string {
  return p?.display_name || p?.email || "—";
}

// --- Report content, styled with plain hex colors rather than the app's
// Tailwind CSS-variable theme (bg-card, text-foreground, etc). This tree is
// rendered off-screen purely for capture, never shown live, so there's no
// reason for it to follow the exporting user's light/dark preference — a
// printed report should look the same regardless. Reusing <KpiCard> or the
// shadcn <Table> here would pull in theme variables that flip under a
// `.dark` ancestor class, which is exactly what this avoids. ---

const th: CSSProperties = {
  textAlign: "left",
  padding: "8px 10px",
  fontSize: 10,
  fontWeight: 700,
  textTransform: "uppercase",
  letterSpacing: 0.4,
  color: "#64748b",
  borderBottom: "2px solid #e2e8f0",
};
